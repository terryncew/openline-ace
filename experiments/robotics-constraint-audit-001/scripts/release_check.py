import json, subprocess
from pathlib import Path

R = Path(__file__).resolve().parents[1]
req = [
    "QUESTION.md",
    "README.md",
    "CLAIM_BOUNDARY.md",
    "SOURCE_PINS.json",
    "experiment_config.json",
    "rca001/__init__.py",
    "rca001/__main__.py",
    "rca001/envelope.py",
    "rca001/core.py",
    "docs/EXTERNAL_RUNNER_PROTOCOL.md",
    "docs/UNITREE_INTEGRATION.md",
    "docs/NOTEBOOKLM_SOURCE.md",
    "scripts/verify_unitree_pin.py",
    "scripts/verify_conformance_independent.py",
    "tests/test_rca001.py",
]

miss = [x for x in req if not (R / x).is_file()]
if miss:
    raise SystemExit(f"missing {miss}")

# Earlier CI steps necessarily create __pycache__/*.pyc in the runner workspace.
# Release closure should reject generated bytecode only when it is committed to
# the repository, not when Python creates it during the run.
repo_root = R.parents[1]
tracked = subprocess.check_output(
    ["git", "-C", str(repo_root), "ls-files", "--", str(R.relative_to(repo_root))],
    text=True,
).splitlines()

tracked_bytecode = [
    p for p in tracked
    if p.endswith(".pyc") or "/__pycache__/" in f"/{p}"
]
if tracked_bytecode:
    raise SystemExit(f"tracked generated bytecode present: {tracked_bytecode}")

print(json.dumps({
    "release_closure": True,
    "file_count": len(req),
    "tracked_bytecode": 0,
    "authority": "NONE",
}, sort_keys=True))
